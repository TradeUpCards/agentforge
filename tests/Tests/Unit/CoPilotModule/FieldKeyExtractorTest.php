/**
 * Unit tests for FieldKeyExtractor implementations.
 *
 * Covers PRD §10 requirement 2 (natural-key stability) and the Risk 1 item
 * ("nk:" prefix collision) raised by the Round-1 team.
 *
 * Tests are fully isolated — no database, no OpenEMR globals required.
 *
 * Cross-teammate Risk 1 (from the Round-1 report):
 *   co_pilot_fhir_links.source_block_id stores both real Docling block ids
 *   AND natural-key strings prefixed with "nk:".  A real Docling block_id
 *   that happens to start with "nk:" would be indistinguishable from a
 *   natural-key carrier in the lookup query.
 *
 *   Our test pins that Docling uses "block_N" format (as generated by
 *   _run_docling_layout in __init__.py, lines 222-233).  A block_id that
 *   starts with "nk:" is therefore outside the Docling output contract.
 *   The test documents this constraint; if Docling ever emits "nk:"-prefixed
 *   ids the disambiguation logic in RoundtripService must be updated.
 *
